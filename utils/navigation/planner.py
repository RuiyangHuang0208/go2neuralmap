"""Navigation module for grid-based path planning on cost maps.

This module provides path planning algorithms for quadruped navigation
on grid-based cost maps generated by the neural map system.
"""

from __future__ import annotations

import heapq
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from enum import Enum, auto
from typing import List, Optional, Tuple

import torch


class PlannerState(Enum):
    """Enumeration of possible planner states."""

    SUCCESS = auto()
    NO_PATH = auto()
    INVALID_START = auto()
    INVALID_GOAL = auto()
    INVALID_MAP = auto()


@dataclass
class PlanResult:
    """Standardized planning result container.

    Attributes:
        state: Planning outcome state (SUCCESS or various failure states).
        path: List of grid coordinates from start to goal (inclusive).
              None if planning failed.
        total_cost: Total path cost (sum of all cell costs along the path).
                    0.0 if planning failed.
    """

    state: PlannerState
    path: Optional[List[Tuple[int, int]]] = None
    total_cost: float = 0.0


@dataclass
class PlannerConfig:
    """Configuration for path planners.

    Attributes:
        obstacle_threshold: Cells with cost >= this value are considered obstacles.
                           Default is 500.0.
    """

    obstacle_threshold: float = 500.0
    waypoint_stride: int = 3


class BasePlanner(ABC):
    """Abstract base class for path planners.

    This class defines the interface for all path planning algorithms.
    Subclasses must implement the ``plan`` method with their specific algorithm.
    """

    def __init__(self, cfg: Optional[PlannerConfig] = None):
        """Initialize the planner.

        Args:
            cfg: Planner configuration. Uses default if not provided.
        """
        self.cfg = cfg if cfg is not None else PlannerConfig()

    @abstractmethod
    def plan(
        self,
        start: Tuple[int, int],
        goal: Tuple[int, int],
        cost_map: torch.Tensor,
    ) -> PlanResult:
        """Plan a path from start to goal on the cost map.

        Args:
            start: Starting grid coordinate (row, col).
            goal: Goal grid coordinate (row, col).
            cost_map: 2D cost map tensor of shape (H, W) or (H, W, 1).

        Returns:
            PlanResult containing the planning outcome.
        """
        pass

    def _validate_inputs(
        self,
        start: Tuple[int, int],
        goal: Tuple[int, int],
        cost_map: torch.Tensor,
    ) -> Optional[PlanResult]:
        """Validate planning inputs and return error result if invalid.

        Args:
            start: Starting grid coordinate.
            goal: Goal grid coordinate.
            cost_map: Cost map tensor.

        Returns:
            PlanResult with error state if validation fails, None if valid.
        """
        # Check cost_map dimensions
        if cost_map.dim() not in (2, 3):
            return PlanResult(
                state=PlannerState.INVALID_MAP,
                path=None,
                total_cost=0.0,
            )

        # Handle (H, W, 1) shape
        if cost_map.dim() == 3:
            if cost_map.shape[2] != 1:
                return PlanResult(
                    state=PlannerState.INVALID_MAP,
                    path=None,
                    total_cost=0.0,
                )
            cost_map_2d = cost_map.squeeze(-1)
        else:
            cost_map_2d = cost_map

        height, width = cost_map_2d.shape

        # Check start coordinate
        if not (0 <= start[0] < height and 0 <= start[1] < width):
            return PlanResult(
                state=PlannerState.INVALID_START,
                path=None,
                total_cost=0.0,
            )

        # Check goal coordinate
        if not (0 <= goal[0] < height and 0 <= goal[1] < width):
            return PlanResult(
                state=PlannerState.INVALID_GOAL,
                path=None,
                total_cost=0.0,
            )

        # Check if start or goal is an obstacle
        if cost_map_2d[start[0], start[1]].item() >= self.cfg.obstacle_threshold:
            return PlanResult(
                state=PlannerState.INVALID_START,
                path=None,
                total_cost=0.0,
            )

        if cost_map_2d[goal[0], goal[1]].item() >= self.cfg.obstacle_threshold:
            return PlanResult(
                state=PlannerState.INVALID_GOAL,
                path=None,
                total_cost=0.0,
            )

        return None

    def _validate_grid_points(
        self,
        start: Tuple[int, int],
        goal: Tuple[int, int],
        height: int,
        width: int,
    ) -> Optional[PlanResult]:
        if not (0 <= start[0] < height and 0 <= start[1] < width):
            return PlanResult(
                state=PlannerState.INVALID_START,
                path=None,
                total_cost=0.0,
            )

        if not (0 <= goal[0] < height and 0 <= goal[1] < width):
            return PlanResult(
                state=PlannerState.INVALID_GOAL,
                path=None,
                total_cost=0.0,
            )

        return None

    def _get_neighbors(self, pos: Tuple[int, int], height: int, width: int) -> List[Tuple[int, int]]:
        """Get valid neighboring cells (8-directional movement).

        Args:
            pos: Current grid position (row, col).
            height: Map height.
            width: Map width.

        Returns:
            List of valid neighbor coordinates.
        """
        row, col = pos
        neighbors = []

        # 8 directions: N, NE, E, SE, S, SW, W, NW
        directions = [
            (-1, 0),  # N
            (-1, 1),  # NE
            (0, 1),  # E
            (1, 1),  # SE
            (1, 0),  # S
            (1, -1),  # SW
            (0, -1),  # W
            (-1, -1),  # NW
        ]

        for dr, dc in directions:
            new_row, new_col = row + dr, col + dc
            if 0 <= new_row < height and 0 <= new_col < width:
                neighbors.append((new_row, new_col))

        return neighbors

    def _get_cardinal_neighbors(self, pos: Tuple[int, int], height: int, width: int) -> List[Tuple[int, int]]:
        row, col = pos
        neighbors = []
        directions = [
            (-1, 0),
            (1, 0),
            (0, -1),
            (0, 1),
        ]

        for dr, dc in directions:
            new_row, new_col = row + dr, col + dc
            if 0 <= new_row < height and 0 <= new_col < width:
                neighbors.append((new_row, new_col))

        return neighbors

    def subsample_waypoints(self, result: PlanResult) -> List[int]:
        """
        Returns sampled waypoints indices in list
        """
        path = result.path

        # Subsample path waypoints (always include last)
        indices = list(range(0, len(path), self.cfg.waypoint_stride))
        if indices[-1] != len(path) - 1:
            indices.append(len(path) - 1)

        return indices
