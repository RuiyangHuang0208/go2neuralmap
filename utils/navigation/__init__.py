"""Navigation module for grid-based path planning.

This module provides path planning algorithms for quadruped navigation
on grid-based cost maps generated by the neural map system.

Example usage:
    >>> import torch
    >>> from utils.navigation import AStarPlanner, PlannerConfig, PathVisualizer

    >>> # Create cost map (10x10 grid)
    >>> cost_map = torch.zeros(10, 10)
    >>> cost_map[5, :] = 100  # Create a low-cost barrier

    >>> # Configure and create planner
    >>> cfg = PlannerConfig(obstacle_threshold=500.0)
    >>> planner = AStarPlanner(cfg)

    >>> # Plan path from (0, 0) to (9, 9)
    >>> result = planner.plan((0, 0), (9, 9), cost_map)
    >>> if result.state.name == "SUCCESS":
    ...     print(f"Path found with cost: {result.total_cost}")
    ...     print(f"Path length: {len(result.path)}")

    >>> # Visualize the result
    >>> visualizer = PathVisualizer()
    >>> fig = visualizer.visualize_path(cost_map, result)
    >>> fig.savefig("path_result.png")
"""

